// Take one dice roll and store the result
const dice1 = Math.floor(Math.random() * 6) + 1;
// Take another dice roll and store the result
const dice2 = Math.floor(Math.random() * 6) + 1;

// Add the two results together and store the result in the variable "result"
const result = dice1 + dice2;

// Print the results to the console
console.log(`Dice 1: ${dice1}, Dice 2: ${dice2}, Result: ${result}`);

